'use strict';
// Bundle only local static CommonJS dependencies; no runtime eval or npm imports.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),modules=new Map();
function collect(relative){
 const absolute=path.resolve(root,relative);
 if(!absolute.startsWith(root+path.sep))throw Error('Outside SIDE1');
 const id=path.relative(root,absolute).replaceAll('\\','/');
 if(modules.has(id))return id;
 const source=fs.readFileSync(absolute,'utf8');modules.set(id,'');
 const code=source.replace(/require\(['"]([^'"]+)['"]\)/g,(_,request)=>{
  if(!request.startsWith('.'))throw Error('Nonlocal dependency: '+request);
  let target=path.resolve(path.dirname(absolute),request);
  if(!path.extname(target))target+='.js';
  return 'load('+JSON.stringify(collect(path.relative(root,target)))+')';
 });
 modules.set(id,code);return id;
}
const entry=collect('services/business_runtime.cjs');
const bundle=`// GENERATED by tools/build_business_edge.cjs. Edit the source modules instead.\nconst factories={\n${[...modules].map(([id,code])=>JSON.stringify(id)+':(module,exports,load)=>{\n'+code+'\n}').join(',\n')}\n};\nconst cache={};\nfunction load(id){if(cache[id])return cache[id].exports;const module={exports:{}};cache[id]=module;factories[id](module,module.exports,load);return module.exports;}\nexport const {runOnce,remoteRpc}=load(${JSON.stringify(entry)});\n`;
const dir=path.join(root,'supabase/functions/side-business-close');fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(dir,'runtime.mjs'),bundle);
console.log(`Bundled ${modules.size} local modules (${Buffer.byteLength(bundle)} bytes).`);
